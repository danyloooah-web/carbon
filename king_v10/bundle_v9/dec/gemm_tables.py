def _fi_into(family, tactic, q, q_scale, weight, weight_scale, out):
    """prefill_gemm._gemm's launch (the rig's fi_call) into a caller-filled output."""
    from flashinfer.gemm import gemm_base

    from bundle_v9.dec import prefill_gemm

    if family != "cute" or not prefill_gemm._CUTE:
        raise RuntimeError(f"no {family} runner to replay")
    work = gemm_base._get_cache_buf("mm_mxfp8_workspace", gemm_base.DEFAULT_WORKSPACE_SIZE, q.device)
    prefill_gemm._CUTE[0](inputs=[q, weight.t(), q_scale, weight_scale, torch.bfloat16, out, work], tactic=tactic)
    return out



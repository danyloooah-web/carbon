def wob(input, weight, weight_scale, input_scale, bias, weight_scale_swizzled, rows):
    """decode_gemm.dg_decode: the WOB-T launch for a proven row, else None (king_v7f's path). The scale must have the
    canonical DeepGEMM layout the proofs used (stride (1, align4(rows)): stock's linear raises on any other, where
    king_v7f's swizzle + CuTe serves it; fixer L1)."""
    entry = _SERVE["wo_b"].get(rows)
    if (entry is None or bias is not None or input_scale is None or input_scale.dtype != torch.int32
            or input.dim() != 2 or not input.is_contiguous() or input.dtype != torch.float8_e4m3fn
            or tuple(input_scale.shape) != (rows, input.shape[-1] // 128)
            or tuple(input_scale.stride()) != (1, -(-rows // 4) * 4) or not _base_ok()):
        return None
    from bundle_v9.dec import decode_gemm

    decode_gemm._trace("wo_b(T)", rows, entry)
    return _dg_linear(entry[1], input, weight, weight_scale, input_scale, weight_scale_swizzled)



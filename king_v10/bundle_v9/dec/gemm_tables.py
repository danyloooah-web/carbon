# ------------------------------------------------------------------------------------------------ proof helpers
def _poison(t):
    """Fill t's whole storage span with NaN bits (0xFF.. for 1- and 4-byte types, NaN for floats)."""
    if t.numel():
        span = 1 + sum((s - 1) * st for s, st in zip(t.shape, t.stride()))
        flat = torch.as_strided(t, (span,), (1,), t.storage_offset())
        if t.dtype in (torch.bfloat16, torch.float16, torch.float32):
            flat.fill_(float("nan"))
        elif t.dtype == torch.int32:
            flat.fill_(-1)
        else:
            flat.view(torch.uint8).fill_(255)
    return t


def _same(a, b) -> bool:
    if a is None or b is None or tuple(a.shape) != tuple(b.shape) or a.dtype != b.dtype:
        return False
    if a.dtype == torch.int32:
        return bool(torch.equal(a, b))
    width = {1: torch.uint8, 2: torch.int16, 4: torch.int32}[a.element_size()]
    return bool(torch.equal(a.contiguous().view(width), b.contiguous().view(width)))


def _healthy(device) -> None:
    try:
        torch.cuda.synchronize(device)
    except Exception as e:  # noqa: BLE001
        raise RuntimeError("bundle-v9 king-v10: the CUDA context faulted inside a GEMM-table proof") from e


def _dg_pair(rows, k, device, gen, lo=120, hi=134):
    """decode_gemm._random_pair with a UE8M0 byte range: fp8 rows and DeepGEMM-packed int32 scales."""
    from sglang.srt.models import deepseek_v4_mhc as mhc

    data = (torch.randn((rows, k), device=device, generator=gen) * 4).to(torch.float8_e4m3fn)
    scale = mhc.empty_deepgemm_mxfp8_scales(rows, k, device)
    span = 1 + sum((n - 1) * st for n, st in zip(scale.shape, scale.stride()))
    raw = torch.randint(lo, hi, (span * 4,), device=device, generator=gen, dtype=torch.uint8)
    torch.as_strided(scale, (span,), (1,), scale.storage_offset()).copy_(raw.view(torch.int32))
    return data, scale


def _spread(rows, k, device, gen, scale=1.0):
    """The rig's seeded input: per-row and per-32-column power-of-two spreads of 2^-7..2^7."""
    x = torch.randn((rows, k), device=device, generator=gen) * scale
    row = torch.randint(-7, 8, (rows, 1), device=device, generator=gen).float().exp2()
    grp = torch.randint(-7, 8, (1, k // 32), device=device, generator=gen).float().exp2()
    return (x * row * grp.repeat_interleave(32, dim=1)).bfloat16()


def _plan(gemm, top, skip=()):
    """[(first, last, entry, graph_rows)]: per table band, the rows <= top where the entry differs from king_v7f's
    static table, minus the graph rows in skip (another lever's rows, NOTES.md section 3)."""
    from bundle_v9.dec import decode_gemm as dg

    def king(rows):
        if gemm in ("wo_b", "wqkv_a"):
            t = dg._tactic(dg.WOB if gemm == "wo_b" else dg.WQKV, rows)
            return ("cute", t) if t is not None else ("deepgemm", None)
        return ("deepgemm", None) if gemm == "wo_a" else ("stock", None)

    plan, lo = [], 1
    for bound, entry in TABLES[gemm]:
        new = [r for r in range(lo, min(bound, top) + 1) if entry != king(r)]
        if new and bound in RIG_KING_BANDS[gemm]:
            raise ValueError(f"rows {new[0]}..{new[-1]} differ from this king's entry inside a band the rig measured "
                             "as the king's own: the table was built against another king")
        graph = tuple(r for r in new if r % GRAPH_STEP == 0 and r not in skip)
        if graph:
            plan.append((new[0], new[-1], entry, graph))
        lo = bound + 1
    # nearest the 240-row bucket first (59 % of the king's decode steps), then 157-192, then the rest
    return sorted(plan, key=lambda b: (0 if b[0] <= 240 <= b[1] else 1 if b[1] >= 157 else 2, abs(240 - b[1])))


def _run(name, plan, deadline, device, rows_check, layers_check):
    """Prove every band; returns (served {rows: entry}, failed, unreached). Failed and unreached bands are reported by
    their graph rows (the skip already removed: fixer F2), never by the table band's span."""
    served, failed, unreached = {}, [], []
    for first, last, entry, rows in plan:
        if time.perf_counter() > deadline:
            unreached.append((rows, entry))
            continue
        why = None
        try:
            for r in rows:
                if time.perf_counter() > deadline:
                    why = "time budget"
                    break
                why = rows_check(r, entry)
                if why:
                    break
            if why is None:
                why = layers_check(rows[-1], entry)
            torch.cuda.synchronize(device)
        except Exception as e:  # noqa: BLE001
            _healthy(device)
            why = f"{type(e).__name__}: {str(e)[:200]}"
        if why is None:
            served.update((r, entry) for r in rows)
        elif why == "time budget":
            unreached.append((rows, entry))
        else:
            failed.append((rows, entry))
            _say(f"{name}: band at graph rows [{_rows_str(rows)}] {entry!r} FAILED ({why}); serves king_v7f's entry")
    return served, failed, unreached


def _report(name, gemm, served, plan, failed, unreached, t0, extra=""):
    _SERVE[gemm] = dict(served)
    if not served:
        _say(f"{name}: off (no band proven: {len(failed)} failed, {len(unreached)} past the {BUDGET_S:.0f} s budget"
             f"); king_v7f's path serves {gemm}")
        return
    tail = f"; {len(failed)} band(s) FAILED" if failed else ""
    if unreached:
        tail += (f"; {len(unreached)} band(s) past the {BUDGET_S:.0f} s budget serve king_v7f's entry: "
                 + ", ".join(f"[{_rows_str(r)}]" for r, _ in unreached))
    _say(f"{name}: ON ({gemm} rig table, {len(plan) - len(failed) - len(unreached)} of {len(plan)} bands served at "
         f"{len(served)} graph rows [{_rows_str(served)}]; bytes equal to king_v7f's path on layer 0 (2 inputs, "
         f"NaN-filled outputs) and at each band top on every layer{extra}{tail}; {time.perf_counter() - t0:.1f} s)")



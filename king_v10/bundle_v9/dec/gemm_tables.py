def prepare(module) -> None:
    """Called last in decode_gemm.prepare (after king_v7f's own proofs, WOBSF-PDL, WQKV288 and DGT). Never raises,
    except on a CUDA context fault inside a proof (re-raised: a sticky fault cannot fail closed)."""

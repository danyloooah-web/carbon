def _rows_str(rows) -> str:
    rows, out, i = sorted(rows), [], 0
    while i < len(rows):
        j = i
        while j + 1 < len(rows) and rows[j + 1] - rows[j] == GRAPH_STEP:
            j += 1
        out.append(f"{rows[i]}" if i == j else f"{rows[i]}-{rows[j]}")
        i = j + 1
    return ",".join(out) or "-"


# ------------------------------------------------------------------------------------------------ DeepGEMM globals
def _bsm_read():
    fn = _BSM_FN[0] if _BSM_FN else None
    if fn is None:
        return _BSM[0]
    value = fn()
    return int(value[0]), int(value[1])


def _bsm_write(m, n) -> None:
    raw = _BSM_FN[1]
    try:  # the rig's form: the python wrapper takes one (m, n) tuple, a raw binding two ints
        raw((int(m), int(n)))
    except TypeError:
        raw(int(m), int(n))
    _BSM[0] = (int(m), int(n))


def _shadow_setter(raw):
    def set_block_size_multiple_of(value):
        m, n = (value, value) if isinstance(value, int) else value
        out = raw(value)
        _BSM[0] = (int(m), int(n))
        return out
    set_block_size_multiple_of.king_v9_raw = raw
    return set_block_size_multiple_of


@contextlib.contextmanager
def _scope(setters):
    """Run a DeepGEMM call under (num_sms, block_m_multiple_of, block_n_multiple_of); None = no setter at all."""
    if setters is None:
        yield
        return
    lib = _DG[0]
    sms, m, n = (int(v) for v in setters)
    prior_sms, prior_bsm = int(lib.get_num_sms()), _bsm_read()
    sms_set = bsm_set = False
    try:
        if sms != prior_sms:
            sms_set = True
            lib.set_num_sms(sms)
        if (m, n) != prior_bsm:
            bsm_set = True
            _bsm_write(m, n)
        yield
    finally:
        if bsm_set:
            _bsm_write(*prior_bsm)
        if sms_set:
            lib.set_num_sms(prior_sms)


def _base_ok() -> bool:
    return bool(_BASE) and (int(_DG[0].get_num_sms()), _bsm_read()) == _BASE[0]


def _dg_prepare(device):
    """None when the DeepGEMM levers may run, else the reason they may not."""
    import deep_gemm

    _DG[:] = [deep_gemm]
    _BASE.clear()
    sms = torch.cuda.get_device_properties(device).multi_processor_count
    if sms != DEVICE_SMS:
        return f"the device has {sms} SMs; the tables were measured on the {DEVICE_SMS}-SM B300"
    needed = (("get_num_sms", getattr(deep_gemm, "get_num_sms", None)),
              ("set_num_sms", getattr(deep_gemm, "set_num_sms", None)),
              ("set_block_size_multiple_of", getattr(deep_gemm, "set_block_size_multiple_of", None)))
    missing = [name for name, fn in needed if not callable(fn)]
    if missing:
        return f"deep_gemm has no {missing[0]}"
    current = deep_gemm.set_block_size_multiple_of
    raw = getattr(current, "king_v9_raw", current)
    getter = getattr(deep_gemm, "get_block_size_multiple_of", None)
    if not callable(getter):
        gm, gn = getattr(deep_gemm, "get_block_m_multiple_of", None), getattr(deep_gemm, "get_block_n_multiple_of", None)
        getter = (lambda: (gm(), gn())) if callable(gm) and callable(gn) else None
    if getter is not None:
        try:
            value = getter()
            getter = getter if len(value) == 2 else None
        except Exception:  # noqa: BLE001
            getter = None
    if getter is None and current is raw:
        # deep_gemm 0.2.3.post2 exports no reader: track every python-level write (the engine and king_v7f make none,
        # so the value is DeepGEMM's HeuristicsRuntime default (1, 1) until one of ours)
        deep_gemm.set_block_size_multiple_of = _shadow_setter(raw)
    _BSM_FN[:] = [getter, raw]
    base = (int(deep_gemm.get_num_sms()), _bsm_read())
    if base != (DEVICE_SMS, (1, 1)):
        return f"the DeepGEMM globals are {base}, not the rig's ({DEVICE_SMS}, (1, 1))"
    _BASE[:] = [base]
    return None



    for served in _SERVE.values():
        served.clear()
    _PREPARED[0] = False
    _SAID.discard("ownership")
    role = str(get_disagg().disaggregation_mode)
    if role != "decode":
        _say(f"GEMM tables: off (role {role}; WOB-T / WOA-T / WQKV-T are decode-only)")
        return
    device = module.layers[0].self_attn.wo_b.weight.device
    t0 = time.perf_counter()
    deadline = t0 + BUDGET_S
    try:
        dg_why = _dg_prepare(device) if (WOB_T_ON or WOA_T_ON) else "no DeepGEMM lever on"
    except Exception as e:  # noqa: BLE001
        dg_why = f"DeepGEMM globals unreadable: {type(e).__name__}: {str(e)[:200]}"
    for name, on, lever, needs_dg in (("WOB-T", WOB_T_ON, _lever_wob, True), ("WQKV-T", WQKV_T_ON, _lever_wqkv, False),
                                      ("WOA-T", WOA_T_ON, _lever_woa, True)):
        if not on:
            _say(f"{name}: off (switched off by gemm_tables.{name.replace('-', '_')}_ON)")
            continue
        if needs_dg and dg_why is not None:
            _say(f"{name}: off ({dg_why})")
            continue
        try:
            lever(module, device, deadline)
        except Exception as e:  # noqa: BLE001
            _healthy(device)
            gemm = {"WOB-T": "wo_b", "WQKV-T": "wqkv_a", "WOA-T": "wo_a"}[name]
